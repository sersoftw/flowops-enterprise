REVOKE ALL ON DATABASE flowops FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
CREATE ROLE orders_app LOGIN PASSWORD 'test_orders' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
CREATE ROLE inventory_app LOGIN PASSWORD 'test_inventory' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE flowops TO orders_app, inventory_app;
CREATE SCHEMA orders AUTHORIZATION orders_app;
CREATE SCHEMA inventory AUTHORIZATION inventory_app;
CREATE ROLE payments_app LOGIN PASSWORD 'test_payments' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
GRANT CONNECT ON DATABASE flowops TO payments_app;
CREATE SCHEMA payments AUTHORIZATION payments_app;
